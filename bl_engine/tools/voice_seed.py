#!/usr/bin/env python3
"""BL VOICE ENGINE — voice_seed.py

작품(프로젝트) 하나를 시작할 때 한 번 돌려서 '이 작품의 손버릇 카드'를 만든다.

왜 필요한가: 2차 블라인드 테스트에서 판별자들은 엔진이 쓴 서로 다른 세 이야기에
같은 손버릇(꼴좋다, 대관절, 다이소, 반문 연타, '그게 왜 보이냐' 끼워 넣기)이
똑같이 나온다는 것으로 AI를 잡아냈다. 사람 작가는 작품마다 버릇이 '조금씩' 다르고,
한 작품 안에서는 버릇이 일정하다. 이 카드는 그 구조를 흉내 낸다.
  - 한 작품 안에서는 카드에 적힌 버릇만 쓴다(일관성).
  - 작품이 바뀌면 다른 시드로 다른 카드를 뽑는다(작품 간 차이).

사용:
  python tools/voice_seed.py "작품 제목"            # 제목으로 시드 고정 → 같은 제목이면 같은 카드
  python tools/voice_seed.py "작품 제목" > PROJECT_VOICE_CARD.md
"""
import hashlib, random, sys

ADVERBS = ['대관절', '도시', '기실', '응당', '짐짓', '공연히', '부러', '애먼', '영락없이', '진배없이', '어지간히',
           '무던히', '사뭇', '자못', '하릴없이', '별안간', '잠자코', '구태여', '퍽', '되레', '외려', '진작',
           '하마터면', '여태', '깜냥껏', '아무튼', '여하튼', '도무지', '하여간', '모쪼록']
CURSES = ['염병', '젠장', '씨', '제기랄', '지랄', '니미', '썅', '빌어먹을', '미친', '개같은', '망할', '존나']
PUNCT = [
    ('침묵 사다리', "상대 대사 사이에 “…….” 한 줄을 끼워 대화가 한쪽으로만 흐르게 한다. 대치 장면에 몰아서 쓰고, 다른 장면에서는 쓰지 않는다."),
    ('느낌표 연타', "코미디·싸움에서 '!!'·'!!!'를 숨김없이 쓴다. 나머지 장면에서는 0."),
    ('하이픈 꼬리', "짧은 대사를 서술 속에 박고 '말.-'로 꼬리를 단다. 나오는 장면에 몰아서."),
    ('꺾쇠 속말', "속으로 삼킨 말이나 남의 말 되새김을 < >로 서술 안에 넣는다."),
    ('홑낫표 회상', "과거 대사는 「 」로, 현재 대사는 “ ”로 구분한다."),
    ('마침표 절단', "감정이 차오르는 문장을 마침표로 중간에 잘라 버린다(그래서. 그냥. 갔다.)."),
]
SIMILE_DOMAINS = ['방송·뉴스', '행정·민원', '음식·배달', '스포츠 중계', '게임', '종교·제사', '군대', '학교·시험',
                  '부동산·이사', '병원·약국', '편의점·마트', '날씨 예보']
OPENINGS = ['이미 싸우는 대사 한복판', '화자가 누군가를 흉보는 서술', '직전 장면 감정을 끌고 온 행동',
            '엉뚱한 물건 하나의 클로즈업', '남이 붙인 별명·소문']
QUESTION_STYLE = [('반문 연타', '혼란할 때 의문문 2~4개를 쌓는다. 혼란한 장면에만.'),
                  ('단발 자문', '의문은 한 번만 던지고 바로 딴소리로 넘어간다.'),
                  ('평서 판정', '의문 대신 현재형 판정 한 줄로 끊는다. 의문문은 몰아서 쓰지 않는다.')]
NONFUNC = [('있음', '덩어리 2개 중 1개에만, 줄거리와 상관없는 구체 하나(상표·노래·가게)를 흘린다.'),
           ('거의 없음', '쓸데없는 구체는 화당 1개 이하. 대신 같은 말을 두 번 하는 사람다운 군더더기를 허용한다.')]


# (v5) 장치 지문: BL 원작 4종 실측. 사람 작가는 장치 몇 개만 '자기 것'으로 쥐고 나머지는 거의 쓰지 않는다.
# (켜질 확률, 켰을 때 덩어리 등장률 범위, 껐을 때 상한)
DEVICES = [
    ('욕', 0.75, (0.40, 0.80), 0.10),
    ("'!!'", 0.40, (0.20, 0.70), 0.0),
    ('침묵 줄 “…….”', 0.65, (0.40, 0.70), 0.05),
    ('고풍 부사', 0.35, (0.10, 0.25), 0.0),
    ('< > 되새김·압축', 0.25, (0.15, 0.50), 0.0),
]


def device_plan(r):
    rows = []
    for name, p_on, (lo, hi), off_cap in DEVICES:
        if r.random() < p_on:
            rows.append((name, '켬', f'덩어리의 {int(r.uniform(lo, hi) * 100)}% 정도에만. 나오는 덩어리에서는 몰아서 쓴다'))
        else:
            rows.append((name, '끔', '이 작품에서는 거의 쓰지 않는다' if off_cap else '이 작품에서는 쓰지 않는다'))
    if sum(1 for _, s, _ in rows if s == '켬') < 2:  # 지문 장치가 하나뿐이면 밋밋하다: 하나 더 켠다
        i = next(i for i, (_, s, _) in enumerate(rows) if s == '끔')
        name, p_on, (lo, hi), _ = DEVICES[i]
        rows[i] = (name, '켬', f'덩어리의 {int(r.uniform(lo, hi) * 100)}% 정도에만. 나오는 덩어리에서는 몰아서 쓴다')
    return rows


def card(title: str) -> str:
    seed = int(hashlib.sha256(title.encode('utf-8')).hexdigest()[:12], 16)
    r = random.Random(seed)
    dev = device_plan(r)
    rhythm_src = sorted(r.sample(['MW', 'HY', 'SD', 'CS'], r.choice([1, 2])))
    on_adv = any(n == '고풍 부사' and s == '켬' for n, s, _ in dev)
    adv = r.sample(ADVERBS, 2 if on_adv else 0)
    state = {n: st for n, st, _ in dev}
    cur = r.sample(CURSES, 2) if state['욕'] == '켬' else []
    blocked = {'침묵 사다리': '침묵 줄 “…….”', '느낌표 연타': "'!!'", '꺾쇠 속말': '< > 되새김·압축'}
    pun = r.sample([x for x in PUNCT if state.get(blocked.get(x[0], ''), '켬') == '켬'], 2)
    sim = r.choice(SIMILE_DOMAINS)
    opn = r.sample(OPENINGS, 2)
    q = r.choice(QUESTION_STYLE)
    nf = r.choice(NONFUNC)
    plain = r.choice([40, 50, 60])
    excl = r.choice(['보통(코미디 장면에 몰아서)', '높음(코미디에서 연타 허용)']) if state["'!!'"] == '켬' else '낮음(느낌표는 드물게, 연타 없음)'
    return f"""# PROJECT VOICE CARD — {title}

이 카드는 이 작품에서만 쓰는 손버릇이다. 카드에 없는 손버릇(다른 고풍 부사, 다른 욕, 다른 문장부호 습관)은 쓰지 않는다.
작품이 바뀌면 새 제목으로 카드를 다시 뽑는다. (시드 {seed % 100000})

| 항목 | 이 작품의 버릇 | 빈도 |
|---|---|---|
| 고풍 부사 | {', '.join(adv) if adv else '(이 작품은 끔)'} | {'켠 경우에도 몇 화에 몰아서. 같은 단어 연속 화 금지' if adv else '쓰지 않는다'} |
| 욕 | {', '.join(cur) if cur else '(이 작품은 끔)'} | {'나오는 장면에 몰아서. 욕이 없는 장면이 더 많다' if cur else '쓰지 않는다'} |
| 문장부호 습관 1 | {pun[0][0]} | {pun[0][1]} |
| 문장부호 습관 2 | {pun[1][0]} | {pun[1][1]} |
| 비유 매개체 영역 | {sim} | 비유는 이 영역 안에서만. 개수를 맞추지 않는다 |
| 장면 여는 방식 | {opn[0]} / {opn[1]} | 번갈아 쓴다 |
| 의문 처리 | {q[0]} | {q[1]} |
| 줄거리와 무관한 구체 | {nf[0]} | {nf[1]} |
| 느낌표 | {excl} | |
| 장치 없는 문단 비율 | 서술 문단의 {plain}% 이상 | 비유·농담·딴소리 없이 사건만 전하는 평범한 문단 |
| 리듬 원천 (v7) | {', '.join(rhythm_src)} | 이 작품의 리듬 악보는 이 원작에서만 뽑는다: `python tools/rhythm_score.py pick --preset 프리셋 --src {','.join(rhythm_src)}` |

## 장치 지문 (v5: 켠 장치만 이 작품의 것이다)

| 장치 | 상태 | 쓰는 법 |
|---|---|---|
{chr(10).join(f'| {n} | {st} | {how} |' for n, st, how in dev)}

장치는 '화당 몇 개' 할당량으로 고르게 깔지 않는다. 켠 장치도 어떤 덩어리에는 몰아서, 어떤 덩어리에는 0개로 둔다.
`python tools/voicecheck.py 1화.md 2화.md 3화.md --series`의 [분포] 항목이 고르게 깔린 장치를 잡는다.

## 이 카드로 쓸 때 지킬 것

- 장치 없는 문단을 반드시 섞는다. 모든 문단에 재치가 있으면 '공들인 모방'으로 읽힌다(2차 블라인드 테스트 판정).
- 복선은 심은 것 중 최소 하나를 회수하지 않는다.
- 다른 작품(다른 카드)에서 쓴 대구·반문 패턴을 이 작품에 가져오지 않는다.
- 이 카드를 원고에 붙이지 않는다. 원고는 산문만.
"""


if __name__ == '__main__':
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(1)
    print(card(' '.join(sys.argv[1:])))
